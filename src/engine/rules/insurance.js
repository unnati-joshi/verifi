function derive(i) {
  const payingYears = i.premiumPayingYears || i.policyTermYears;
  return {
    coverMultiple: Number((i.sumAssured / i.annualPremium).toFixed(1)),
    totalPremium: Math.round(i.annualPremium * payingYears),
    premiumToIncomePct: i.annualIncome ? Number(((i.annualPremium / i.annualIncome) * 100).toFixed(1)) : null,
    coverToIncome: i.annualIncome ? Number((i.sumAssured / i.annualIncome).toFixed(1)) : null,
  };
}

